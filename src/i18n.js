  function t(text, params) {
    var table = DICT[locale];
    var out = (table && table[text]) || text;
    if (!params) return out;
    return String(out).replace(/\{(\w+)\}/g, function (m, key) {
      return params[key] == null ? m : String(params[key]);
    });
  }

  function plural(key, n) {
    var forms = (PLURALS[locale] && PLURALS[locale][key]) || (PLURALS.ru && PLURALS.ru[key]);
    if (!forms) return String(n);
    var cat = new Intl.PluralRules(locale).select(Math.abs(Number(n) || 0));
    var out = forms[cat] || forms.other || forms.many || forms.one || String(n);
    return out.replace('{n}', String(n));
  }

  function setLocale(code) {
    if (code !== 'ru' && code !== 'en' && code !== 'es') return false;
    locale = code;
    try { root.localStorage.setItem(LOCALE_KEY, code); } catch (e) {}
    return true;
  }

  root.I18n = {
    t: t,
    plural: plural,
    locale: function () { return locale; },
    setLocale: setLocale,
    locales: LOCALES,
  };
